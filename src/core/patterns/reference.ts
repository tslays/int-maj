/**
 * The hand index: how the books file the catalogue, as data.
 *
 * Nothing here decides a rule. It records where each hand is printed and
 * under which heading, so the table can offer a searchable reference instead
 * of two books:
 *
 *   - `SYNOPSIS`: the headings of the Companion's "Full synopsis of special
 *     hands" [C pp. 56-61], each with its rows in printed order and the page
 *     the row points to (`null` where the book prints N/I, not illustrated).
 *     A hand filed under several headings is listed under each, as printed.
 *   - `ILLUSTRATED_PAGES`: the printed page of every hand in *The Game of Mah
 *     Jong Illustrated*, from rules/RULES.md Part II. A hand absent from this
 *     map is printed only in the Companion.
 *   - `EXAMPLES`: one complete example of each hand, the same tiles as the
 *     positive fixture in test/core/catalogue.test.ts.
 *
 * The synopsis prints Big Robert once; both of its scoring variants are filed
 * there. Its last page [C p. 61] sorts the pung hands into three columns
 * (same suit, different suits, all honours) without page numbers; they are
 * one heading here. Two hands printed only in the Illustrated list on p. 30,
 * All Kong and Mixed Pung, are filed under that heading by their composition
 * (`EDITORIAL_ROWS`); the synopsis does not print them.
 */

export interface SynopsisHeading {
  /** Stable id, used as the filter key. */
  readonly id: string;
  /** The heading, in the book's words. */
  readonly name: string;
  /** The Companion page the heading is printed on. */
  readonly page: number;
  /** Rows in printed order: the page the row cites (null = N/I) and the hand. */
  readonly rows: readonly (readonly [page: number | null, pattern: string])[];
}

